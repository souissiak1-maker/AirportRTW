#include "../rtw80211/openbsd/net80211/ieee80211_ptk.hpp"
#include "../rtw80211/sae/rtw_sae_crypto.h"
#include <assert.h>
// Independent HMAC-based KDF callbacks verify the actual production PTK inputs.
static void sha256(const uint8_t *key,size_t kl,const uint8_t *label,size_t ll,
                   const uint8_t *ctx,size_t cl,uint8_t *out,size_t length)
{
    uint8_t bits[2]={uint8_t(length*8),uint8_t(length*8>>8)};
    for(unsigned n=1;length;++n) {
        uint8_t count[2]={uint8_t(n),uint8_t(n>>8)},hash[32];
        const uint8_t *pieces[]={count,label,ctx,bits};size_t sizes[]={2,ll,cl,2};
        rtw_sae_hmac_sha256_vector(key,kl,4,pieces,sizes,hash);
        size_t take=length<32?length:32;memcpy(out,hash,take);out+=take;length-=take;
    }
}
static void sha1(const uint8_t *key,size_t kl,const uint8_t *label,size_t ll,
                 const uint8_t *ctx,size_t cl,uint8_t *out,size_t length)
{
    for(uint8_t n=0;length;++n) {
        uint8_t hash[20];const uint8_t *pieces[]={label,ctx,&n};size_t sizes[]={ll,cl,1};
        rtw_sae_hmac_sha1_vector(key,kl,3,pieces,sizes,hash);
        size_t take=length<20?length:20;memcpy(out,hash,take);out+=take;length-=take;
    }
}
int main()
{
    uint8_t pmk[32],a[32],s[32],out[64];
    for(unsigned i=0;i<32;++i) { pmk[i]=i;a[i]=i;s[i]=i+32; }
    const uint8_t aa[]={0,0x11,0x22,0x33,0x44,0x55},spa[]={0x66,0x77,0x88,0x99,0xaa,0xbb};
    const uint8_t sae[]={0xb3,0x97,0x52,0x56,0xbc,0x53,0x90,0xd2,0x17,0xb0,0x2b,0x7f,0x53,0x1c,0x22,0x28,0x21,0x1b,0x29,0x18,0x9c,0x62,0xe9,0x02,0x66,0x2d,0x47,0x29,0x4d,0xe6,0xe1,0xb2,0x18,0x3f,0xbb,0xf8,0xa9,0xe9,0xa2,0xd3,0xb7,0x22,0x92,0x37,0x64,0xf3,0xd2,0xf8};
    const uint8_t wpa[]={0x79,0xc3,0x15,0x81,0x7d,0xa2,0xce,0x91,0x7e,0x32,0x64,0xee,0xac,0x39,0xf9,0x08,0xed,0xaf,0xe7,0x82,0x05,0xab,0x10,0xe5,0xfa,0x4d,0x85,0x50,0x52,0x35,0xf6,0x96,0xad,0x89,0x09,0x20,0x24,0xc3,0x45,0x24,0xf0,0x7b,0x21,0xe1,0xf7,0xba,0xf3,0xb4,0x76,0xe2,0xb3,0xf0,0x64,0xf8,0x10,0xeb,0x14,0x07,0x08,0xbe,0x96,0x8d,0x02,0xf3};
    Net80211PTK::derive(true,pmk,aa,spa,a,s,out,sizeof(out),sha256);
    assert(!memcmp(out,sae,sizeof(sae)));
    for(unsigned i=48;i<64;++i) assert(out[i]==0);
    Net80211PTK::derive(true,pmk,spa,aa,s,a,out,sizeof(out),sha256);
    assert(!memcmp(out,sae,sizeof(sae)));
    Net80211PTK::derive(false,pmk,aa,spa,a,s,out,sizeof(out),sha1);
    assert(!memcmp(out,wpa,sizeof(wpa)));
}
